"""Numerically verify the manuscript's analytical statements and keep docs/THEORY.md current.

    python -B scripts/verify_theory.py                      # quick battery (seconds), exit 1 on any FAIL
    python -B scripts/verify_theory.py --full               # larger samples (about a minute)
    python -B scripts/verify_theory.py --only lemma-2 theorem-2
    python -B scripts/verify_theory.py --json-output reports/theory.json --markdown reports/theory.md
    python -B scripts/verify_theory.py --write-doc          # regenerate docs/THEORY.md
    python -B scripts/verify_theory.py --check-doc          # battery plus a currency check of docs/THEORY.md

NumPy and the standard library only; no PyTorch, data or network. The battery
draws randomized instances of every statement's hypotheses with a fixed seed and
tests the conclusion (cm_theory/verification.py). Passing checks show that the
implementations, printed constants and stated assumptions agree on the instances
drawn; they do not replace the supplementary proofs.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from cm_theory import STATEMENTS  # noqa: E402
from cm_theory import admission, budget, inference, operators, spectral  # noqa: E402
from cm_theory.verification import CHECK_STATEMENT, DEFAULT_SEED, run_battery  # noqa: E402

DOC = ROOT / "docs" / "THEORY.md"


def _code(items) -> str:
    return "<br>".join(f"`{item}`" for item in items)


def reference_values() -> list[tuple[str, str, str]]:
    """Deterministic constants implied by the statements at the registered settings."""
    actions = operators.transport_actions()
    windows = spectral.chebyshev_window_coefficients()
    eps = ", ".join(f"{spectral.window_error(windows[b], b):.3f}" for b in range(len(windows)))
    rows = [
        ("Lemma 2", "truncation bound 2(1-eta)^9 at T = 8 for eta = 0.50, 0.20, 0.08",
         ", ".join(f"{2 * (1 - eta) ** 9:.4f}" for eta in (0.5, 0.2, 0.08))),
        ("Eq. (10)", "executed range h_a of A0-A7 (hops per step)",
         ", ".join(f"{operators.executed_range(a):.3f}" for a in actions)),
        ("Eq. (10)", "identity coefficient of A0-A7", ", ".join(f"{operators.identity_coefficient(a):.3f}" for a in actions)),
        ("Proposition 6", "conservative global window-error bounds eps_b (with grid remainder)", eps),
        ("Note S19", "relative SD bound sqrt(2/k) at k = 16, 32, 64",
         ", ".join(f"{budget.sketch_relative_sd_bound(k):.3f}" for k in (16, 32, 64))),
        ("Theorem 2 / Corollary 2", "numerator constant 14 B log(2/delta_a)/3 at B = 0.10, delta_a = 0.025",
         f"{admission.corollary2_constant():.5f} nats"),
        ("Corollary 2", "second penalty term at J = 10, 32, 64",
         ", ".join(f"{admission.bernstein_terms(0.0, J, 0.10, 0.025)['fixed_term']:.4f}" for J in (10, 32, 64))),
        ("Proposition 7", "Hoeffding regret bound 2e(n) at n = 64, 74, 142 (B = 0.10, \\|A\\| = 10, delta = 0.05)",
         ", ".join(f"{2 * admission.hoeffding_radius(n):.4f}" for n in (64, 74, 142))),
        ("Proposition 7", "units for 2e(n) <= 0.003 (Hoeffding, real-valued requirement)",
         f"{8 * 0.01 * math.log(400) / 0.003 ** 2:,.1f}"),
        ("Proposition 7", "Bernstein-below-Hoeffding crossover and units for 2e_B <= 0.003 at sigma_1 = 0.007",
         f"n = {admission.bernstein_crossover(0.007)}; n = {admission.units_for_bernstein_regret(0.003, 0.007):,}"),
        ("Eq. (7)", "maximum normalized weight implied by ESS >= 64 and ESS >= 32",
         f"{admission.weight_cap_from_ess(64):.3f}, {admission.weight_cap_from_ess(32):.4f}"),
        ("Methods", "minimum detectable effect multipliers (80% power): two-sided 0.05; first Holm step of four",
         f"{inference.minimum_detectable_effect():.4f}; {inference.minimum_detectable_effect(family_size=4):.4f}"),
    ]
    return rows


def render_doc(result: dict) -> str:
    claims: dict[str, list[str]] = {}
    for row in result["rows"]:
        claims.setdefault(row["statement_key"], [])
        label = row["claim"] + (" *(reference value)*" if row["status"] == "INFO" else "")
        if label not in claims[row["statement_key"]]:
            claims[row["statement_key"]].append(label)
    checks_by_statement: dict[str, list[str]] = {}
    for name, key in CHECK_STATEMENT.items():
        checks_by_statement.setdefault(key, []).append(name)
    lines = [
        "# Analytical statements: implementation and numerical verification",
        "",
        "<!-- Generated by `python -B scripts/verify_theory.py --write-doc`; `make verify` checks that it is current. -->",
        "",
        "Every definition, lemma, proposition, theorem and corollary of the main text, the Supplementary Lemma 3 "
        "(work bound of Algorithm S3) and the equations whose arithmetic the lifecycle executes have an explicit "
        "reference implementation in [`cm_theory/`](../cm_theory/) and a numerical check in "
        "[`cm_theory/verification.py`](../cm_theory/verification.py). Each check draws randomized instances of the "
        "statement's hypotheses (random graphs including periodic ones, random states, bounded loss distributions, "
        "finite decision processes, budgets and cost bounds) with a fixed seed and tests the conclusion; identities "
        "are tested to floating-point precision and Monte Carlo coverage statements against the nominal level plus "
        "three binomial standard errors. Where an executable component of this repository implements the "
        "statement, the check runs that component: `cross_morse.statistics.empirical_bernstein` for Theorem 2, "
        "`cm_experiments.budget.run_budget_episode` for Lemma 3 and the Holm adjustments of the runtime and of the "
        "campaign tools.",
        "",
        "```bash",
        "make theory           # quick battery (seconds); part of make verify",
        "make theory-full      # larger samples",
        "python -B scripts/verify_theory.py --only theorem-2 --json-output \"$REPORT_ROOT/theory.json\"",
        "```",
        "",
        "Scope: a passing check shows that the implementation, the printed constants and the stated assumptions "
        "agree on the instances drawn. It is not a proof (the proofs are in Supplementary Notes S8-S26), it does "
        "not test whether a statement's hypotheses hold for a trained backbone, and it makes no claim about "
        "predictive benefit. The arithmetic of the manuscript's derived table entries is checked separately by "
        "`scripts/check_paper_constants.py` and `scripts/check_si_identities.py` (`make si-check`).",
        "",
        "## Map",
        "",
        "| Statement | Source | Reference implementation | Runtime counterpart | Checks |",
        "|---|---|---|---|---|",
    ]
    for s in STATEMENTS:
        names = checks_by_statement.get(s.key, [])
        lines.append(f"| **{s.label}** {s.title} | {s.source} | {_code(s.theory)} | {'<br>'.join(s.runtime)} | "
                     f"{_code(names)} |")
    lines += ["", "## Statements and verified claims", ""]
    for s in STATEMENTS:
        lines += [f"### {s.label}: {s.title}", "", f"*Source:* {s.source}.", "", s.claim, "", "Verified:", ""]
        lines += [f"- {claim}" for claim in claims.get(s.key, [])]
        lines += ["", f"*Scope:* {s.limits}", ""]
    lines += ["## Reference values at the registered settings", "",
              "Deterministic values implied by the statements; the battery checks the printed counterparts.", "",
              "| Statement | Quantity | Value |", "|---|---|---|"]
    lines += [f"| {a} | {b} | {c} |" for a, b, c in reference_values()]
    lines.append("")
    return "\n".join(lines)


def render_report(result: dict) -> str:
    lines = [f"# Theory battery ({result['mode']}, seed {result['seed']})", "",
             f"PASS {result['counts']['PASS']}, FAIL {result['counts']['FAIL']}, INFO {result['counts']['INFO']}", "",
             "Counts describe assertion rows emitted by numerical check generators, not proofs or benchmark reproduction.", "",
             "| status | statement | claim | observed | bound | instances | detail |", "|---|---|---|---|---|---|---|"]
    for row in result["rows"]:
        observed = json.dumps(row["observed"])[:120].replace("|", "/")
        bound = json.dumps(row["bound"])[:60].replace("|", "/")
        lines.append(f"| {row['status']} | {row['statement']} | {row['claim'].replace(chr(124), '/')} | {observed} | {bound} | {row['instances']} | {row['detail'].replace(chr(124), '/')} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--full", action="store_true", help="larger samples (about a minute)")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--only", nargs="+", metavar="KEY", help="statement keys (e.g. theorem-2) or check names")
    parser.add_argument("--json-output", type=Path, help="write all rows as JSON")
    parser.add_argument("--markdown", type=Path, help="write a Markdown report with observed values")
    parser.add_argument("--write-doc", action="store_true", help="regenerate docs/THEORY.md")
    parser.add_argument("--check-doc", action="store_true", help="fail when docs/THEORY.md is not current")
    parser.add_argument("--quiet", action="store_true", help="print failures and the summary only")
    args = parser.parse_args(argv)
    if (args.write_doc or args.check_doc) and (args.only or args.full or args.seed != DEFAULT_SEED):
        parser.error("--write-doc/--check-doc use the default quick battery")
    try:
        result = run_battery(quick=not args.full, seed=args.seed, only=args.only)
    except KeyError as exc:
        print(f"unknown statement or check: {exc}", file=sys.stderr)
        return 2
    by_statement: dict[str, list[int]] = {}
    for row in result["rows"]:
        tally = by_statement.setdefault(row["statement_key"], [0, 0, 0])
        tally[0 if row["status"] == "PASS" else 1 if row["status"] == "FAIL" else 2] += 1
    if not args.quiet:
        labels = {s.key: s.label for s in STATEMENTS}
        print(f"{'statement':24s} {'pass':>5s} {'fail':>5s} {'info':>5s}")
        for key, (ok, fail, info) in by_statement.items():
            print(f"{labels.get(key, key):24s} {ok:5d} {fail:5d} {info:5d}")
    for row in result["rows"]:
        if row["status"] == "FAIL":
            print(f"FAIL [{row['statement']}] {row['claim']}: observed={row['observed']!r} bound={row['bound']!r} {row['detail']}")
    counts = result["counts"]
    print(f"{counts['PASS']} of {counts['PASS'] + counts['FAIL']} analytical checks passed "
          f"({len(by_statement)} statement groups, {result['check_generators_selected']} check generators, "
          f"{result['mode']} battery, seed {result['seed']}; {counts['INFO']} reference values)")
    if result["statements_without_checks"]:
        print("statements without checks: " + ", ".join(result["statements_without_checks"]))
    for path, text in ((args.json_output, json.dumps(result, indent=2) + "\n"),
                       (args.markdown, render_report(result) if args.markdown else None)):
        if path is not None:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    status = 1 if counts["FAIL"] or result["statements_without_checks"] else 0
    if (args.write_doc or args.check_doc) and status:
        print("Documentation was not generated or certified: required analytical checks failed or are missing.")
        return status
    if args.write_doc:
        DOC.write_text(render_doc(result), encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)}")
    if args.check_doc:
        current = DOC.read_text(encoding="utf-8") if DOC.is_file() else ""
        if current != render_doc(result):
            print(f"{DOC.relative_to(ROOT)} is not current; run: python -B scripts/verify_theory.py --write-doc")
            status = 1
        else:
            print(f"{DOC.relative_to(ROOT)} is current")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
